"""delivery-kit hourly auto-sync — a no-agent hermes cron job.

Every connected provider with a live fetcher gets pulled hourly during the
working day (08:00-19:00 in the USER'S timezone — the dashboard sends the
browser's offset on load, so DST corrects itself on the next visit). The job
is `no_agent`: a generated script under ~/.hermes/scripts/ runs on schedule
with zero LLM cost, stays silent (empty stdout = no delivery), and drops its
results into the settings file for the dashboard to show.
"""
from __future__ import annotations

import json
import logging
import os
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)

SYNC_JOB_NAME = "delivery-kit-sync"
SCRIPT_NAME = "delivery-kit-sync.py"
DEFAULT_START_HOUR = 8               # window defaults: 08:00-19:00 inclusive,
DEFAULT_END_HOUR = 19                # user-local
DEFAULT_FREQ_MINUTES = 60
FREQ_CHOICES = (30, 60, 120, 180, 240)


def _home() -> Path:
    return Path(os.environ.get("HERMES_HOME", os.path.expanduser("~/.hermes")))


def _settings_path() -> Path:
    return _home() / "delivery-kit-autosync.json"


def load_settings() -> dict:
    try:
        return json.loads(_settings_path().read_text())
    except Exception:
        return {}


def save_settings(s: dict) -> None:
    p = _settings_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(s, indent=2))


def _cron_expr(tz_offset_minutes: int,
               start_hour: int = DEFAULT_START_HOUR,
               end_hour: int = DEFAULT_END_HOUR,
               freq_minutes: int = DEFAULT_FREQ_MINUTES) -> str:
    """User-local sync window + frequency -> container-TZ cron expr.

    tz_offset_minutes is JS getTimezoneOffset(): minutes to ADD to local
    time to get UTC (240 for EDT, -330 for IST). Containers run UTC
    (Railway); the stored offset keeps the window on the user's clock.
    Window is start..end inclusive in the user's local clock; freq_minutes
    picks the cadence within it (30 = twice hourly, 120 = every other hour).
    Minute x hour lists are a cross product, so a non-hour-aligned offset
    with freq<60 can add near-boundary runs — harmless for a sync job.
    """
    off = int(tz_offset_minutes)
    start = min(23, max(0, int(start_hour)))
    end = min(23, max(0, int(end_hour)))
    if end < start:
        start, end = end, start
    freq = int(freq_minutes) if int(freq_minutes) in FREQ_CHOICES \
        else DEFAULT_FREQ_MINUTES
    hour_step = max(1, freq // 60)
    minute_marks = range(0, 60, freq) if freq < 60 else (0,)

    minutes, hours = set(), set()
    for hh in range(start, end + 1, hour_step):
        for mm in minute_marks:
            total = (hh * 60 + mm + off) % (24 * 60)
            minutes.add(total % 60)
            hours.add(total // 60)
    minute_part = ",".join(str(m) for m in sorted(minutes))
    hour_part = ",".join(str(h) for h in sorted(hours))
    return f"{minute_part} {hour_part} * * *"


_SCRIPT_TEMPLATE = '''#!/usr/bin/env python3
"""Generated by the delivery-kit plugin — hourly provider auto-sync.

Hermes no-agent cron job: syncs every connected provider that has a live
fetcher. Empty stdout keeps the run silent; results land in the autosync
settings file for the dashboard.
"""
import importlib.util
import json
import sys
import time
from pathlib import Path

PLUGIN_ROOT = {plugin_root!r}
PKG = "hermes_plugin_pkg_delivery_kit"

if PKG not in sys.modules:
    spec = importlib.util.spec_from_file_location(
        PKG, str(Path(PLUGIN_ROOT) / "__init__.py"),
        submodule_search_locations=[PLUGIN_ROOT])
    mod = importlib.util.module_from_spec(spec)
    sys.modules[PKG] = mod
    spec.loader.exec_module(mod)

import importlib
providers = importlib.import_module(PKG + ".providers")
store = importlib.import_module(PKG + ".store")

results = {{}}
for p in providers.PROVIDERS:
    pid = p["id"]
    if not p.get("canSync") or not p.get("env"):
        continue
    if not providers.get_key(p["env"]):
        continue
    try:
        fetched = providers.sync_provider(pid, limit=25)
        new = 0
        for t in fetched:
            _, was_new = store.upsert_meeting(
                pid, t["externalId"], t["title"], t["heldAt"],
                t["durationMin"], t["transcript"], t["providerSummary"])
            new += 1 if was_new else 0
        results[pid] = {{"ok": True, "fetched": len(fetched), "new": new}}
    except Exception as exc:
        results[pid] = {{"ok": False, "error": str(exc)[:200]}}

settings_path = Path({settings_path!r})
try:
    prev = json.loads(settings_path.read_text())
except Exception:
    prev = {{}}
prev["lastRun"] = time.time()
prev["results"] = results
settings_path.write_text(json.dumps(prev, indent=2))
# stdout intentionally empty -> silent cron delivery
'''


def _write_script() -> Path:
    scripts_dir = _home() / "scripts"
    scripts_dir.mkdir(parents=True, exist_ok=True)
    path = scripts_dir / SCRIPT_NAME
    path.write_text(_SCRIPT_TEMPLATE.format(
        plugin_root=str(Path(__file__).resolve().parent),
        settings_path=str(_settings_path())))
    return path


def autosync_status() -> dict:
    """Cheap read for /state — no cron import, just the settings file."""
    s = load_settings()
    return {
        "enabled": bool(s.get("enabled", True)),
        "configured": "cronJobId" in s,
        "tzOffsetMinutes": s.get("tzOffsetMinutes"),
        "startHour": int(s.get("startHour", DEFAULT_START_HOUR)),
        "endHour": int(s.get("endHour", DEFAULT_END_HOUR)),
        "frequencyMinutes": int(s.get("frequencyMinutes", DEFAULT_FREQ_MINUTES)),
        "lastRun": s.get("lastRun"),
        "results": s.get("results"),
    }


def ensure_sync_job(tz_offset_minutes: Optional[int] = None,
                    enabled: Optional[bool] = None,
                    start_hour: Optional[int] = None,
                    end_hour: Optional[int] = None,
                    frequency_minutes: Optional[int] = None) -> dict:
    """Create or update the scheduled sync job to match settings."""
    from cron import jobs as cron_jobs

    s = load_settings()
    if tz_offset_minutes is not None:
        s["tzOffsetMinutes"] = int(tz_offset_minutes)
    if enabled is not None:
        s["enabled"] = bool(enabled)
    if start_hour is not None:
        s["startHour"] = min(23, max(0, int(start_hour)))
    if end_hour is not None:
        s["endHour"] = min(23, max(0, int(end_hour)))
    if frequency_minutes is not None and int(frequency_minutes) in FREQ_CHOICES:
        s["frequencyMinutes"] = int(frequency_minutes)
    s.setdefault("enabled", True)
    s.setdefault("tzOffsetMinutes", 0)
    s.setdefault("startHour", DEFAULT_START_HOUR)
    s.setdefault("endHour", DEFAULT_END_HOUR)
    s.setdefault("frequencyMinutes", DEFAULT_FREQ_MINUTES)

    _write_script()
    expr = _cron_expr(s["tzOffsetMinutes"], s["startHour"], s["endHour"],
                      s["frequencyMinutes"])

    job = None
    if s.get("cronJobId"):
        job = cron_jobs.resolve_job_ref(s["cronJobId"])
    if job is None:
        job = cron_jobs.resolve_job_ref(SYNC_JOB_NAME)

    if job is None:
        if s["enabled"]:
            job = cron_jobs.create_job(
                prompt=None, schedule=expr, name=SYNC_JOB_NAME,
                deliver="local", script=SCRIPT_NAME, no_agent=True)
            s["cronJobId"] = job["id"]
            logger.info("delivery-kit: created auto-sync job %s (%s)",
                        job["id"], expr)
    elif s["enabled"]:
        cron_jobs.update_job(job["id"], {
            "schedule": expr,
            "script": SCRIPT_NAME,
            "no_agent": True,
            "enabled": True,
        })
        s["cronJobId"] = job["id"]
    else:
        # OFF means gone — no zombie disabled jobs on the Cron tab;
        # re-enabling recreates the job from scratch
        cron_jobs.remove_job(job["id"])
        s.pop("cronJobId", None)

    save_settings(s)
    st = autosync_status()
    st["schedule"] = expr
    return st
